"""Example plugin (extra_files): openapi.json describing the generated API, for every framework.

FastAPI serves its own schema at /docs; Flask and Django do not. This file is built from the
design itself, so Postman, Insomnia, Swagger UI or a client generator can use any of them.
"""

import json

from agent.tools import routes

DESCRIPTION = "Adds openapi.json (OpenAPI 3.1) built from the design, for any framework"
WHEN = "other systems integrate with the API (SDKs, partners, third parties, API docs)"
KEYWORDS = ("openapi", "swagger", "sdk", "integration", "third-party", "third party")

_TYPES = {"str": "string", "text": "string", "int": "integer", "float": "number", "decimal": "number",
          "bool": "boolean", "date": "string", "datetime": "string", "json": "object"}
_FORMATS = {"date": "date", "datetime": "date-time"}


def _schema(e) -> dict:
    props, required = {}, []
    for f in e.fields:
        prop = {"type": _TYPES.get(f.type, "string")}
        if f.type in _FORMATS:
            prop["format"] = _FORMATS[f.type]
        if f.choices:
            prop["enum"] = list(f.choices)
        if f.min is not None:
            prop["minimum"] = f.min
        if f.max is not None:
            prop["maximum"] = f.max
        if f.references:
            prop = {"type": "integer", "description": f"id of a {f.references}"}
        props[f.name] = prop
        if f.required:
            required.append(f.name)
    return {"type": "object", "properties": props, "required": required}


def _operation(method: str, path: str, spec) -> dict:
    table = path.strip("/").split("/")[0]
    entity = next((e for e in spec.entities if e.table == table), None)
    op = {"summary": f"{method} {path}", "responses": {"200": {"description": "OK"}}}
    if entity:
        op["tags"] = [entity.name]
        ref = {"$ref": f"#/components/schemas/{entity.name}"}
        if method == "POST" and path.endswith(f"/{table}/"):
            op["requestBody"] = {"required": True, "content": {"application/json": {"schema": ref}}}
            op["responses"] = {"201": {"description": "Created"}, "409": {"description": "Conflict"},
                               "422": {"description": "Invalid input"}}
        if method == "PATCH":
            op["requestBody"] = {"content": {"application/json": {"schema": ref}}}
        if method == "DELETE":
            op["responses"] = {"204": {"description": "Deleted"}}
    if "{item_id}" in path:
        op["parameters"] = [{"name": "item_id", "in": "path", "required": True, "schema": {"type": "integer"}}]
    if spec.auth and not path.startswith(("/health", "/auth/register", "/auth/login")):
        op["security"] = [{"bearer": []}]
    return op


def extra_files(spec) -> dict[str, str]:
    paths: dict = {}
    for route in routes(spec):
        method, path = route.split(" ", 1)
        paths.setdefault(path, {})[method.lower()] = _operation(method, path, spec)
    doc = {
        "openapi": "3.1.0",
        "info": {"title": spec.project_name.replace("_", " ").title(), "version": "1.0.0",
                 "description": spec.description or "Generated by VibeStack"},
        "servers": [{"url": "http://localhost:8000"}],
        "paths": paths,
        "components": {"schemas": {e.name: _schema(e) for e in spec.entities},
                       "securitySchemes": {"bearer": {"type": "http", "scheme": "bearer", "bearerFormat": "JWT"}}},
    }
    return {"openapi.json": json.dumps(doc, indent=2) + "\n"}
