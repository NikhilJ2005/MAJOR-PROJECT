import json
import sys
import urllib.error
import urllib.request

AUTH = __AUTH__
PLAN = __PLAN__


def call(method, url, body=None, token=None):
    data = json.dumps(body).encode() if body is not None else None
    request = urllib.request.Request(url, data=data, method=method, headers={"Content-Type": "application/json"})
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request) as response:
            return response.status, json.loads(response.read() or b"null")
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read().decode()


def main():
    args = sys.argv[1:]
    base = (args[0] if args and not args[0].startswith("--") else "http://localhost:8000").rstrip("/")
    email = args[args.index("--email") + 1] if "--email" in args else "admin@example.com"
    password = args[args.index("--password") + 1] if "--password" in args else "seed-password-123"
    token = None
    if AUTH:
        call("POST", f"{base}/auth/register", {"email": email, "password": password})
        status, body = call("POST", f"{base}/auth/login", {"email": email, "password": password})
        if status != 200:
            sys.exit(f"login failed ({status}): {body}")
        token = body["access_token"]
    made = {}
    for entity in PLAN:
        made[entity["name"]] = []
        for row in entity["rows"]:
            for key, value in list(row.items()):
                if isinstance(value, str) and value.startswith("@ref:"):
                    _, target, index = value.split(":")
                    ids = made.get(target) or [None]
                    row[key] = ids[int(index) % len(ids)]
            status, body = call("POST", f"{base}/{entity['table']}/", row, token)
            if status == 201:
                made[entity["name"]].append(body["id"])
            else:
                print(f"  skipped a {entity['name']}: {status} {str(body)[:120]}")
        print(f"{entity['name']}: {len(made[entity['name']])} rows")


if __name__ == "__main__":
    main()
