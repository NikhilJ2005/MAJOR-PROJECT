"""Example plugin (extra_files): scripts/seed.py fills a running app with realistic sample rows.

It talks to the app's own HTTP API (so it works the same for FastAPI, Flask and Django), creates
rows in dependency order (a comment after its post) and links foreign keys to the rows it made:

    python scripts/seed.py http://localhost:8000 --email admin@example.com
"""

import json

DESCRIPTION = "Adds scripts/seed.py: fills a running app with sample rows (links, choices, value ranges)"
ROWS = 5


def _order(spec) -> list:
    """Entities so that every referenced entity comes before the ones pointing at it."""
    done, ordered = set(), []
    pending = list(spec.entities)
    while pending:
        for e in pending:
            needs = {f.references for f in e.fields if f.references and f.references != "User"}
            if needs <= done or not any(x.name in needs for x in pending if x is not e):
                ordered.append(e)
                done.add(e.name)
                pending.remove(e)
                break
        else:  # a cycle: keep the given order for the rest
            ordered += pending
            break
    return ordered


def _value(e, f, i: int):
    """A plausible value for row i: rotate choices, spread numbers inside min/max, vary text."""
    if f.references:
        return None if f.references == "User" else f"@ref:{f.references}:{i}"
    if f.choices:
        return f.choices[i % len(f.choices)]
    if f.type in ("int", "float", "decimal"):
        low = f.min if f.min is not None else 1
        high = f.max if f.max is not None else low + 100
        value = low + (high - low) * (i + 1) / (ROWS + 1)
        return int(value) if f.type == "int" else round(value, 2)
    if f.type == "bool":
        return i % 2 == 0
    if f.type == "date":
        return f"2026-0{1 + i % 9}-1{i % 9}"
    if f.type == "datetime":
        return f"2026-0{1 + i % 9}-1{i % 9}T10:00:00"
    if f.type == "json":
        return {"example": i + 1}
    words = f"{f.name.replace('_', ' ')} {i + 1}"
    return f"{e.name} {words}" + (" - sample text for the demo" if f.type == "text" else "")


def extra_files(spec) -> dict[str, str]:
    plan = []
    for e in _order(spec):
        rows = []
        for i in range(ROWS):
            row = {f.name: _value(e, f, i) for f in e.fields}
            rows.append({k: v for k, v in row.items() if v is not None})
        plan.append({"name": e.name, "table": e.table, "rows": rows})
    return {"scripts/seed.py": SCRIPT.replace("__PLAN__", json.dumps(plan, indent=1)).replace("__AUTH__", str(spec.auth))}


